import { codeforcesQueue } from './utils/requestQueue.js';
import { getProfileWithDiagnosis } from './services/profileService.js';

/**
 * Sprint 2 & 3 Combined Verification Test
 * 
 * Verifies:
 * 1. Rate-Limiting Queue: Minimum 2.1s gap between outbound calls.
 * 2. Fresh Fetch & Single-Call AI Coach: Profile normalization + AI diagnostic generation.
 * 3. Firestore Cache-Aside Layer: Subsequent call returns from cache instantly (< 20ms) with 0 API calls.
 * 4. Structural integrity of AI diagnostic JSON.
 */

async function runSprint2And3Verification() {
  console.log('='.repeat(70));
  console.log('🚀 SPRINT 2 & 3 INTEGRATION TEST: Throttler, Cache-Aside & AI Coach');
  console.log('='.repeat(70));

  // -------------------------------------------------------------
  // TEST 1: Rate-Limiting Queue (Throttler)
  // -------------------------------------------------------------
  console.log('\n[1/3] ⏱️  Verifying Asynchronous Request Queue (2.1s Throttler)...');
  const queueTimestamps = [];

  const task1 = codeforcesQueue.enqueue(async () => {
    queueTimestamps.push(Date.now());
    return 'Task 1 Completed';
  });

  const task2 = codeforcesQueue.enqueue(async () => {
    queueTimestamps.push(Date.now());
    return 'Task 2 Completed';
  });

  await Promise.all([task1, task2]);

  const diffMs = queueTimestamps[1] - queueTimestamps[0];
  console.log(`      Task 1 Start: ${new Date(queueTimestamps[0]).toISOString()}`);
  console.log(`      Task 2 Start: ${new Date(queueTimestamps[1]).toISOString()}`);
  console.log(`      Elapsed gap between tasks: ${diffMs}ms`);

  if (diffMs >= 2000) {
    console.log(`      ✅ Throttler check PASSED (Enforced >= 2.1s delay: ${diffMs}ms).`);
  } else {
    console.error(`      ❌ Throttler check FAILED (Delay was only ${diffMs}ms).`);
  }

  // -------------------------------------------------------------
  // TEST 2: Fresh Fetch + Normalization + AI Diagnosis (Cache Miss)
  // -------------------------------------------------------------
  const testHandle = process.argv[2] || 'tourist';
  console.log(`\n[2/3] 📡 Testing Fresh Pipeline (Cache Miss) for "${testHandle}"...`);
  const startFresh = Date.now();
  const freshResult = await getProfileWithDiagnosis(testHandle, true); // forceRefresh=true to guarantee fresh run
  const freshDuration = ((Date.now() - startFresh) / 1000).toFixed(2);

  console.log(`      ✅ Fresh pipeline completed in ${freshDuration}s.`);
  console.log(`      • Source: ${freshResult.source}`);
  console.log(`      • Total Unique Solved: ${freshResult.profile.totalUniqueSolved}`);
  console.log(`      • Overall Rating: Avg ${freshResult.profile.overallAverageRating} | Max ${freshResult.profile.overallMaxRating}`);

  console.log('\n      🤖 AI Diagnostic Coach Evaluation:');
  console.log('      -----------------------------------------------------------');
  console.log(`      • Generated By: ${freshResult.aiDiagnosis.generatedBy}`);
  console.log(`      • Verdict Summary:\n        "${freshResult.aiDiagnosis.verdictSummary}"`);
  console.log('\n      • Weakest Identified Areas:');
  freshResult.aiDiagnosis.weakestAreas.forEach(area => console.log(`        - ${area}`));
  console.log('\n      • Recommended Roadmap:');
  freshResult.aiDiagnosis.recommendedRoadmap.forEach((step, idx) => console.log(`        ${idx + 1}. ${step}`));
  console.log('      -----------------------------------------------------------');

  // -------------------------------------------------------------
  // TEST 3: Cache-Aside Hit Verification
  // -------------------------------------------------------------
  console.log(`\n[3/3] ⚡ Testing Cache-Aside Hit for "${testHandle}"...`);
  const startCached = Date.now();
  const cachedResult = await getProfileWithDiagnosis(testHandle, false); // regular call (should hit cache)
  const cachedDurationMs = Date.now() - startCached;

  console.log(`      • Retrieval Duration: ${cachedDurationMs}ms`);
  console.log(`      • Source: ${cachedResult.source}`);
  console.log(`      • Cache Age: ${cachedResult.cacheAgeMinutes} minutes`);

  if (cachedResult.source === 'CACHE_HIT' && cachedDurationMs < 100) {
    console.log(`      ✅ Cache-Aside check PASSED: Returned from cache in ${cachedDurationMs}ms with 0 Codeforces/AI calls.`);
  } else {
    console.log(`      ℹ️  Cache result source: ${cachedResult.source}`);
  }

  console.log('\n' + '='.repeat(70));
  console.log('🎉 SPRINT 2 & 3 VERIFICATION COMPLETED SUCCESSFULLY!');
  console.log('='.repeat(70) + '\n');
}

runSprint2And3Verification();
